package com.agri.rental.service;

import com.agri.rental.domain.Booking;
import com.agri.rental.domain.Notification;
import com.agri.rental.domain.User;
import com.agri.rental.repository.BookingRepository;
import com.agri.rental.repository.NotificationRepository;
import com.agri.rental.repository.UserRepository;

import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

@Service
public class NotificationService {

    private final NotificationRepository notificationRepository;
    private final UserRepository userRepository;
    private final BookingRepository bookingRepository;

    public NotificationService(
            NotificationRepository notificationRepository,
            UserRepository userRepository,
            BookingRepository bookingRepository) {

        this.notificationRepository = notificationRepository;
        this.userRepository = userRepository;
        this.bookingRepository = bookingRepository;
    }


    // =========================================================
    // CREATE RENTAL EXPIRY NOTIFICATION
    // =========================================================

    @Transactional
    public Notification createRentalExpiryNotification(
            Long bookingId) {

        Booking booking =
                bookingRepository.findById(bookingId)
                        .orElseThrow(() ->
                                new RuntimeException(
                                        "Booking not found"
                                ));

        User user = booking.getUser();

        if (user == null) {

            throw new RuntimeException(
                    "Booking has no user"
            );
        }


        // -----------------------------------------------------
        // Prevent duplicate expiry notifications
        // -----------------------------------------------------

        boolean alreadyExists =
                notificationRepository
                        .existsByBookingIdAndType(
                                bookingId,
                                "RENTAL_EXPIRED"
                        );

        if (alreadyExists) {

            return null;
        }


        // -----------------------------------------------------
        // Create notification
        // -----------------------------------------------------

        Notification notification =
                new Notification();

        notification.setUser(user);

        notification.setBooking(booking);

        notification.setTitle(
                "Rental Expired"
        );

        notification.setMessage(
                "Your equipment rental time has ended. " +
                        "Please request equipment pickup."
        );

        notification.setType(
                "RENTAL_EXPIRED"
        );

        notification.setRead(false);

        return notificationRepository.save(
                notification
        );
    }


    // =========================================================
    // CREATE DELIVERY OTP NOTIFICATION
    // =========================================================
    //
    // Called when delivery partner arrives at farmer location.
    //
    // OTP is generated by DeliveryService.
    // This method only creates the farmer notification.
    //
    // OTP validity:
    // 10 minutes
    //
    // =========================================================

    @Transactional
    public Notification createDeliveryOtpNotification(
            Long bookingId,
            String otp,
            LocalDateTime otpExpiresAt) {

        // -----------------------------------------------------
        // Find booking
        // -----------------------------------------------------

        Booking booking =
                bookingRepository.findById(bookingId)
                        .orElseThrow(() ->
                                new RuntimeException(
                                        "Booking not found"
                                ));


        // -----------------------------------------------------
        // Get farmer
        // -----------------------------------------------------

        User farmer = booking.getUser();

        if (farmer == null) {

            throw new RuntimeException(
                    "Booking has no farmer."
            );
        }


        // -----------------------------------------------------
        // Validate OTP information
        // -----------------------------------------------------

        if (otp == null || otp.trim().isEmpty()) {

            throw new RuntimeException(
                    "OTP is required."
            );
        }

        if (otpExpiresAt == null) {

            throw new RuntimeException(
                    "OTP expiry time is required."
            );
        }


        // -----------------------------------------------------
        // Format expiry time
        // -----------------------------------------------------

        String expiryTime =
                otpExpiresAt.format(
                        DateTimeFormatter.ofPattern(
                                "hh:mm a"
                        )
                );


        // -----------------------------------------------------
        // Create notification
        // -----------------------------------------------------

        Notification notification =
                new Notification();

        notification.setUser(farmer);

        notification.setBooking(booking);

        notification.setTitle(
                "🚚 Delivery Partner Has Arrived"
        );


        String message =
                "Your delivery partner has arrived. " +
                        "Your OTP is " + otp + ". " +
                        "This OTP is valid for 10 minutes. " +
                        "Please provide it to the delivery partner " +
                        "before it expires. " +
                        "Expires at " + expiryTime + ".";


        notification.setMessage(message);

        notification.setType(
                "DELIVERY_OTP"
        );

        notification.setRead(false);


        return notificationRepository.save(
                notification
        );
    }


    // =========================================================
    // CREATE OVERDUE REMINDER
    // =========================================================
    //
    // Called by vendor when farmer has not returned equipment.
    //
    // =========================================================

    @Transactional
    public Notification createOverdueReminder(
            Long bookingId,
            Long vendorUserId) {

        // -----------------------------------------------------
        // Find booking
        // -----------------------------------------------------

        Booking booking =
                bookingRepository.findById(bookingId)
                        .orElseThrow(() ->
                                new RuntimeException(
                                        "Booking not found"
                                ));


        // -----------------------------------------------------
        // Validate booking status
        // -----------------------------------------------------

        if (!"OVERDUE".equalsIgnoreCase(
                booking.getStatus())) {

            throw new RuntimeException(
                    "Reminder can only be sent for overdue bookings."
            );
        }


        // -----------------------------------------------------
        // Get equipment
        // -----------------------------------------------------

        if (booking.getEquipment() == null) {

            throw new RuntimeException(
                    "Booking has no equipment."
            );
        }


        // -----------------------------------------------------
        // Get equipment vendor
        // -----------------------------------------------------

        User vendor =
                booking.getEquipment().getVendor();

        if (vendor == null) {

            throw new RuntimeException(
                    "Equipment has no vendor."
            );
        }


        // -----------------------------------------------------
        // SECURITY CHECK
        // -----------------------------------------------------
        // Only the vendor who owns the equipment can
        // send the reminder.
        // -----------------------------------------------------

        if (!vendor.getId().equals(vendorUserId)) {

            throw new RuntimeException(
                    "You are not allowed to send this reminder."
            );
        }


        // -----------------------------------------------------
        // Get farmer
        // -----------------------------------------------------

        User farmer =
                booking.getUser();

        if (farmer == null) {

            throw new RuntimeException(
                    "Booking has no farmer."
            );
        }


        // -----------------------------------------------------
        // Create reminder notification
        // -----------------------------------------------------

        Notification notification =
                new Notification();

        notification.setUser(farmer);

        notification.setBooking(booking);

        notification.setTitle(
                "⚠️ Overdue Rental Reminder"
        );


        String message =
                "Your rental is overdue. " +
                        "Please return the equipment as soon as possible. " +
                        "Current overdue charges: ₹"
                        + String.format(
                        "%.2f",
                        booking.getExtraCharges()
                );


        notification.setMessage(message);

        notification.setType(
                "OVERDUE_REMINDER"
        );

        notification.setRead(false);


        return notificationRepository.save(
                notification
        );
    }


    // =========================================================
    // GET ALL NOTIFICATIONS OF USER
    // =========================================================

    public List<Notification> getUserNotifications(
            Long userId) {

        if (!userRepository.existsById(userId)) {

            throw new RuntimeException(
                    "User not found"
            );
        }


        return notificationRepository
                .findByUserIdOrderByCreatedAtDesc(
                        userId
                );
    }


    // =========================================================
    // GET UNREAD NOTIFICATION COUNT
    // =========================================================

    public long getUnreadCount(Long userId) {

        if (!userRepository.existsById(userId)) {

            throw new RuntimeException(
                    "User not found"
            );
        }


        return notificationRepository
                .countByUserIdAndReadFalse(
                        userId
                );
    }


    // =========================================================
    // MARK NOTIFICATION AS READ
    // =========================================================

    @Transactional
    public Notification markAsRead(
            Long notificationId,
            Long userId) {

        Notification notification =
                notificationRepository
                        .findById(notificationId)
                        .orElseThrow(() ->
                                new RuntimeException(
                                        "Notification not found"
                                ));


        // -----------------------------------------------------
        // Security check
        // -----------------------------------------------------

        if (notification.getUser() == null ||
                !notification.getUser()
                        .getId()
                        .equals(userId)) {

            throw new RuntimeException(
                    "You are not allowed to modify this notification"
            );
        }


        notification.setRead(true);


        return notificationRepository.save(
                notification
        );
    }


    // =========================================================
    // MARK ALL NOTIFICATIONS AS READ
    // =========================================================

    @Transactional
    public void markAllAsRead(Long userId) {

        List<Notification> notifications =
                notificationRepository
                        .findByUserIdOrderByCreatedAtDesc(
                                userId
                        );


        for (Notification notification :
                notifications) {

            notification.setRead(true);
        }


        notificationRepository.saveAll(
                notifications
        );
    }


    // =========================================================
    // DELETE DELIVERY OTP NOTIFICATIONS
    // =========================================================
    //
    // Used after OTP verification.
    //
    // All DELIVERY_OTP notifications belonging to the
    // booking will be permanently removed.
    //
    // =========================================================

    @Transactional
    public void deleteDeliveryOtpNotifications(
            Long bookingId) {

        if (bookingId == null) {
            return;
        }

        notificationRepository
                .deleteByBookingIdAndType(
                        bookingId,
                        "DELIVERY_OTP"
                );
    }
}